/**
 * Post-deploy script: reads Hardhat Ignition artifacts and generates
 * apps/web/src/lib/addresses.ts with real contract addresses.
 *
 * Usage:
 *   node scripts/update-addresses.mjs <network>
 *
 * Example:
 *   node scripts/update-addresses.mjs arbitrum-sepolia
 *
 * Prerequisites:
 *   1. Deploy contracts: cd packages/contracts && npm run deploy:sepolia
 *   2. Run this script from project root
 */

import { readFileSync, writeFileSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const projectRoot = join(__dirname, "..");

const network = process.argv[2] || "arbitrum-sepolia";

// Map network to chain ID
const chainIds = {
  "arbitrum-sepolia": 421614,
  "arbitrum": 42161,
  "avalanche-fuji": 43113,
  "avalanche": 43114,
  "polygon-amoy": 80002,
  "polygon": 137,
  "optimism-sepolia": 11155420,
  "base-sepolia": 84532,
  "bsc-testnet": 97,
  "fantom-testnet": 4002,
  "aurora-testnet": 1313161555,
  "celo-alfajores": 44787,
  "cronos-testnet": 338,
  localhost: 31337,
};

const chainId = chainIds[network];
if (!chainId) {
  console.error(`Unknown network: ${network}`);
  console.error(`Supported: ${Object.keys(chainIds).join(", ")}`);
  process.exit(1);
}

// Ignition artifact names (from deploy output)
const contracts = [
  { key: "EVOLVE", module: "EVOLVE", artifact: "evolveToken" },
  { key: "PROFILE_NFT", module: "ProfileNFT", artifact: "profileNFT" },
  { key: "TRUST_SCORE", module: "TrustScore", artifact: "trustScore" },
  { key: "VOTING", module: "TrustScore", artifact: "voting" },
  { key: "EVOLVE_2_EARN", module: "Evolve2Earn", artifact: "evolve2Earn" },
  { key: "GOVERNANCE", module: "Governance", artifact: "governance" },
  { key: "BOND_MANAGER", module: "BondManager", artifact: "bondManager" },
  { key: "EVOLVE_FUND", module: "EvolveFund", artifact: "evolveFund" },
  { key: "VERIFICATION_REGISTRY", module: "VerificationRegistry", artifact: "registry" },
  { key: "DNA_VERIFICATION", module: "DNAVerification", artifact: "dnaVerification" },
];

// Try to read from Ignition deployment artifacts
const ignitionDir = join(
  projectRoot,
  "packages",
  "contracts",
  "ignition",
  "deployments",
  `chain-${chainId}`,
);

const addresses = {};

for (const contract of contracts) {
  const artifactPath = join(ignitionDir, `${contract.module}.sol`, `${contract.artifact}.json`);
  try {
    const artifact = JSON.parse(readFileSync(artifactPath, "utf-8"));
    addresses[contract.key] = artifact.address;
    console.log(`✅ ${contract.key}: ${artifact.address}`);
  } catch {
    console.log(`⚠️  ${contract.key}: not found (deployment artifact missing)`);
    addresses[contract.key] = "0x0000000000000000000000000000000000000000";
  }
}

// Also look for the main deployment file
const mainArtifactPath = join(ignitionDir, "_module.json");
let moduleName = "DeployAllModule";
try {
  const mainArtifact = JSON.parse(readFileSync(mainArtifactPath, "utf-8"));
  // Extract addresses from main deployment
  for (const [key, val] of Object.entries(mainArtifact.contracts || {})) {
    if (val.address) {
      // Try to match by name
      for (const contract of contracts) {
        if (key.includes(contract.artifact)) {
          addresses[contract.key] = val.address;
          console.log(`✅ ${contract.key}: ${val.address} (from _module.json)`);
        }
      }
    }
  }
} catch {
  // _module.json not found, that's ok
}

// If no addresses found from artifacts, try alternative: hardhat-ignition-deployments
const altPath = join(
  projectRoot,
  "packages",
  "contracts",
  ".ignition",
  "deployments",
  `chain-${chainId}`,
);
try {
  const entries = require("fs").readdirSync(altPath);
  console.log(`Found alternative artifacts in: ${altPath}`);
} catch {
  // No alternative artifacts
}

// Generate addresses.ts
const addressesFile = `/**
 * Centralized contract addresses for Evolve platform.
 * Generated by scripts/update-addresses.mjs after testnet deploy.
 *
 * Network: ${network} (chainId: ${chainId})
 * Generated: ${new Date().toISOString()}
 */

// ─── ${network} (chainId: ${chainId}) ───
export const CONTRACTS = {
  EVOLVE: "${addresses.EVOLVE}",
  PROFILE_NFT: "${addresses.PROFILE_NFT}",
  TRUST_SCORE: "${addresses.TRUST_SCORE}",
  VOTING: "${addresses.VOTING}",
  EVOLVE_2_EARN: "${addresses.EVOLVE_2_EARN}",
  GOVERNANCE: "${addresses.GOVERNANCE}",
  BOND_MANAGER: "${addresses.BOND_MANAGER}",
  EVOLVE_FUND: "${addresses.EVOLVE_FUND}",
  VERIFICATION_REGISTRY: "${addresses.VERIFICATION_REGISTRY}",
  DNA_VERIFICATION: "${addresses.DNA_VERIFICATION}",
} as const;

/** Network chain ID */
export const CHAIN_ID = ${chainId};

/** Network name */
export const NETWORK_NAME = "${network}";

// ─── Re-export individual addresses for backward-compatible imports ───
export const GOVERNANCE_ADDRESS = CONTRACTS.GOVERNANCE as \`0x\${string}\`;
export const FUND_ADDRESS = CONTRACTS.EVOLVE_FUND as \`0x\${string}\`;
export const BOND_MANAGER_ADDRESS = CONTRACTS.BOND_MANAGER as \`0x\${string}\`;
export const TRUST_SCORE_ADDRESS = CONTRACTS.TRUST_SCORE as \`0x\${string}\`;
`;

const outputPath = join(projectRoot, "apps", "web", "src", "lib", "addresses.ts");
writeFileSync(outputPath, addressesFile, "utf-8");

console.log(`\n📝 Updated ${outputPath}`);
console.log(`Network: ${network} (chainId: ${chainId})`);
